/*---------------------------------------------------------------------------*/
void ssd1306_WriteString(const char *str)
{
    while (str && *str)
    {
        uint8_t ch = (uint8_t)(*str++);

        if (ch >= 'a' && ch <= 'z')   /* 小写折叠为大写，取用已验证字模 */
            ch -= ('a' - 'A');

        if (ch >= 0x20 && ch <= 0x7E)
        {
            const uint8_t *g = font6x8[ch - 0x20];

            if (cur_x + 6 <= SSD1306_WIDTH)
            {
                for (uint8_t c = 0; c < 6; c++)   /* 5 列点阵 + 1 列间隔 */
                    ssd1306_buf[cur_page * SSD1306_WIDTH + cur_x + c] = g[c];
                cur_x += 6;
            }
        }
        /* 换行：\n 跳到下一页开头 */
        else if (ch == '\n')
        {
            cur_x = 0;
            if (cur_page < SSD1306_PAGES - 1)
                cur_page++;
        }
    }
}
