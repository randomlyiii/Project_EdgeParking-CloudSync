/**
 ******************************************************************************
 * @file    ssd1306.c
 * @brief   0.96" OLED (SSD1306, 128x64, I2C) driver for STM32MP1 M4 (HAL)
 *
 *          硬件连接（100ASK-MP157，I2C1 分配给 M4）：
 *            OLED VCC  -> 3.3V      OLED GND -> GND
 *            OLED SCL  -> PF14(I2C1_SCL)     OLED SDA -> PF15(I2C1_SDA)
 *
 *          依赖 CubeMX 生成的 hi2c1（声明在 i2c.h）。
 *          本驱动自带 1024B 显示缓存，画字后调用 ssd1306_Update() 上屏。
 ******************************************************************************
 */
#include "ssd1306.h"
#include "main.h"          /* HAL 类型 */
#include "i2c.h"           /* extern I2C_HandleTypeDef hi2c1; */

#define SSD1306_CTRL_CMD   0x00u   /* 控制字节：后续均为命令 */
#define SSD1306_CTRL_DATA  0x40u   /* 控制字节：后续均为显存数据 */

/* 显示缓存（页格式：128 列 x 8 页） */
static uint8_t ssd1306_buf[SSD1306_BUFFER_SIZE];

/* 当前光标 */
static uint8_t cur_x = 0;
static uint8_t cur_page = 0;

/*---------------------------------------------------------------------------*/
static void ssd1306_SendCmd(uint8_t cmd)
{
    uint8_t d[2];
    d[0] = SSD1306_CTRL_CMD;
    d[1] = cmd;
    HAL_I2C_Master_Transmit(&hi2c1, SSD1306_I2C_ADDR, d, 2, 100);
}

static void ssd1306_SendCmds(const uint8_t *cmds, uint16_t len)
{
    uint8_t d[SSD1306_WIDTH];
    uint16_t i, chunk;

    while (len > 0)
    {
        chunk = (len > (SSD1306_WIDTH - 1)) ? (SSD1306_WIDTH - 1) : len;
        d[0] = SSD1306_CTRL_CMD;
        for (i = 0; i < chunk; i++)
            d[i + 1] = cmds[i];
        HAL_I2C_Master_Transmit(&hi2c1, SSD1306_I2C_ADDR, d, chunk + 1, 100);
        cmds += chunk;
        len  -= chunk;
    }
}

/*---------------------------------------------------------------------------*/
void ssd1306_Init(void)
{
    /* SSD1306 标准初始化序列（128x64，内部电荷泵） */
    static const uint8_t init_cmds[] = {
        0xAE,       /* display off                     */
        0xD5, 0x80, /* 时钟分频                        */
        0xA8, 0x3F, /* 多路复用 1/64                   */
        0xD3, 0x00, /* 显示偏移 0                      */
        0x40,       /* 起始行 0                        */
        0x8D, 0x14, /* 电荷泵开                        */
        0x20, 0x00, /* 寻址模式：水平                  */
        0xA1,       /* 段重映射（0xA0 则为镜像）        */
        0xC8,       /* COM 扫描方向（0xC0 则上下颠倒）  */
        0xDA, 0x12, /* COM 引脚配置                    */
        0x81, 0xCF, /* 对比度                          */
        0xD9, 0xF1, /* 预充电周期                      */
        0xDB, 0x40, /* VCOMH 选择                      */
        0xA4,       /* 恢复 RAM 显示                   */
        0xA6,       /* 正常显示（非反色）              */
        0x2E,       /* 关闭滚动                        */
        0xAF        /* display on                      */
    };

    ssd1306_SendCmds(init_cmds, sizeof(init_cmds));
    ssd1306_Clear(0);
    ssd1306_Update();
}

void ssd1306_Update(void)
{
    uint8_t d[SSD1306_WIDTH + 1];   /* 129B，避免占用过多栈 */
    uint8_t page;

    /* 每页先设页地址再写 128 字节显存 */
    for (page = 0; page < SSD1306_PAGES; page++)
    {
        uint8_t cmds[4];
        cmds[0] = SSD1306_CTRL_CMD;
        cmds[1] = 0xB0 + page;          /* 设置页地址 */
        cmds[2] = 0x00;                 /* 列低字节 */
        cmds[3] = 0x10;                 /* 列高字节 */
        HAL_I2C_Master_Transmit(&hi2c1, SSD1306_I2C_ADDR, cmds, 4, 100);

        d[0] = SSD1306_CTRL_DATA;
        for (uint16_t i = 0; i < SSD1306_WIDTH; i++)
            d[i + 1] = ssd1306_buf[page * SSD1306_WIDTH + i];
        HAL_I2C_Master_Transmit(&hi2c1, SSD1306_I2C_ADDR, d,
                                SSD1306_WIDTH + 1, 100);
    }
}

void ssd1306_Clear(uint8_t fill)
{
    for (uint16_t i = 0; i < SSD1306_BUFFER_SIZE; i++)
        ssd1306_buf[i] = fill ? 0xFF : 0x00;
}

void ssd1306_SetCursor(uint8_t x, uint8_t page)
{
    cur_x = (x < SSD1306_WIDTH) ? x : (SSD1306_WIDTH - 6);
    cur_page = (page < SSD1306_PAGES) ? page : (SSD1306_PAGES - 1);
}

