def _resolve_models():
    """在 KPU_DIRS 里找模型文件，返回 (det, recog, weight, dir)。

    ⭐ ROI_MODE=1 时**只要求识别模型 + 权重**：检测模型压根不加载，所以卡上没有
    `lp_detect.kmodel` 也必须能跑（2026-09-15 补：原来 min() 要求三件齐全，固定
    ROI 策略省掉的第一个文件反而成了硬依赖）。此时返回的 det 路径只是"约定位置"，
    调用方不会去用它（`kpu_load_detect()` 在 ROI_MODE 直接返回）。
    都没找齐则返回首选路径 + None（调用方据此报错并列出搜索过的目录）。"""
    need = KPU_PATH_TAIL[1:] if ROI_MODE else KPU_PATH_TAIL
    for d in KPU_DIRS:
        ps = [d + "/" + n for n in need]
        if min(_exists(p) for p in ps):
            if ROI_MODE:
                # det 不参与，但路径按**同一个目录**给，免得 found 与 det 目录打架
                return d + "/" + KPU_PATH_TAIL[0], ps[0], ps[1], d
            return ps[0], ps[1], ps[2], d
    ps = [KPU_DIR + "/" + n for n in KPU_PATH_TAIL]
    return ps[0], ps[1], ps[2], None


