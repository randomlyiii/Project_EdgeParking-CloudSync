# ---- GC 堆体检（2026-09-13 源码定案：**只读 + 只许抬高**）---------------------
# K210 的内存来自**一个池子**，开机时被切成两块（CanMV 1.0.7 **源码**定案）：
#   GC 堆    —— MicroPython 变量/**连 park_app.py 自己的字节码与编译期语法树都在里面**
#  系统堆   —— 图像/AI/LCD/**模型与权重**，`maix.utils.heap_free()` 可查
#
# ⭐ **两块是 1:1 的真交易**：`maixpy_main.c` 开机 `gc_heap = malloc(gc_heap_size)`
#   —— 给 GC 堆的每一字节都是从模型那个池子里拿的（`malloc` 失败会回退 128KB 并打印
#   "GC heap size N is too large"，所以"过大"能自愈、"过小"才致命）。
#   `gc_heap_size(N)` 本身**只把数字写进 SPIFFS 的 freq.conf，本次运行不动划分**
#   （`Maix_utils.c`）⇒ 必须**重启一次**才生效；我们看到的 `deferred` 是设计如此。
#   实测 `sys_free + gc_heap` ≈ 2.97~3.04MB 是个固定池，且方向单调：
#   gc=750KB→sys 2152KB、gc=512KB→sys 2456KB、gc=404KB→sys 2504KB。
#   （早先"两次冷启动 sys_free 一字未变"的记录是**那次写入还没生效**，
#     "两块内存不互相让"的结论已作废。）
#
# ⛔ 但**自动压小仍然禁止**，因为下限未知、代价是砖机：
#   写到 253952 之后开机只剩 `MemoryError: memory allocation failed, allocating
#   160 bytes` —— park_app.py **编译期峰值**（源码+语法树+字节码）远大于常驻的 ~108KB，
#   248KB 不够编译。已知 **404 / 464 / 512KB 能起，248KB 起不来**。
#   ⇒ 现在：**低于 HEAP_TUNE_GC_MIN 才把它抬回固件默认值；永不自动压小。**
#      要再往下压，必须先在板上量出"park_app.py 能编译"的真实下限再加余量，不许试值。
#   ⇒ 系统堆那边最大的**一笔**增量在**固件**：厂家 FULL 镜像 2.07MB vs Lite 1.55MB，
#      而 K210 没有外部 DRAM、代码与数据同在 6MB SRAM 里 ⇒ 正文少 ~520KB，
#      留给堆的就多 ~520KB（厂家车牌例程自己写着"仅支持 Lite 版 CanMV 固件"）。
#      换固件前后各跑一次 `k210_fw/tools/fw_probe.py` 冷启动，用 [BUD] 那行实测定案。
HEAP_TUNE = 1                     # 置 0 = 连体检都不做
HEAP_TUNE_GC_MIN = 384 * 1024     # 低于此值 park_app.py 可能**编译不出来**（实测 248KB 挂）
# 抬回去的目标 = 512KB。⛔ 2026-09-17 **回退**：当天曾把它提到 768KB（想替 09-16 的
#   启动器兜住那个堆），真机对比却相反 ——
#     512KB：连跑 12.2 分钟 / 233 次识别 / 367 次 [stat]，mem_free 一直 310~367KB（无泄漏）
#     768KB：~2 秒就抛**裸 TypeError**（崩在 `[stat]` 那行的 `%` 上，见 run() 2744 行）
#   768KB 要从系统堆多拿 256KB+（实测 cam_init 处 sys_free 1101824 → 839680），模型/
#   相机那边更紧。**在查清"谁写坏了 GC 堆"之前不要再用 768KB。** 本函数永远只读+只抬高。
HEAP_TUNE_GC_RESTORE = 512 * 1024
HEAP_TUNE_NEED = 2660 * 1024      # 系统堆"够装模型+权重+相机"的参考线（只用于打印判断）
# 冷启动该有多少系统堆（2026-09-13 实测 2564096）。远低于它 = **这不是冷启动**：
# IDE 点「Run」/软重启**不会归还**上一次 KPU 占的模型内存（实测 2.5MB -> 144KB），
# 于是识别模型读 65 秒、权重必然失败、重试还会一路泄漏 ⇒ 数据全无意义。
COLD_BOOT_MIN_FREE = 1800 * 1024


def _apply_gc_heap(target):
    """把 GC 堆改成 target，并验证它**当场**生效。返回 (status, before, after)。

    status:
      "live"     —— 系统堆确实动了（划分当场换了，调用方可以按新余量继续）
      "deferred" —— 调用没报错、但系统堆一点没动：这块固件把生效推迟到下次上电
      "failed"   —— maix.utils 不可用，或 gc_heap_size() 直接抛异常（划分没改成）

    不迷信"设了就一定变"：设完再看一眼系统堆。把 deferred 和 failed 分开是要紧的
    ——前者要喊用户冷启动，后者喊了也没用（划分根本没动）。
    ⚠️ 判据只能是"变了没有"，**不能**假设方向：调小 GC 堆会让系统堆变大（权重要
    的就是这个），但"把被压坏的 GC 堆拉回下限"会让系统堆变小——两个方向都算 live。
    """
    u, _ = _maix_utils()
    if u is None:
        return "failed", -1, -1
    before, _ = _sys_heap_free()
    try:
        u.gc_heap_size(target)
    except Exception as e:
        print("[MEM] gc_heap_size(%d) failed: %r" % (target, e))
        return "failed", before, before
    try:
        gc.collect()
    except Exception:
        pass
    after, _ = _sys_heap_free()
    return ("live" if after != before else "deferred"), before, after


def _gc_floor(cur, gc_free):
    """park_app.py 自己吃掉多少 GC 堆（诊断用，**不再用来算下限**）。

    `used = gc_heap - gc_free` = 加载到这里为止的常驻占用（字节码 + 模块级常量 +
    类对象）。注意它**不含编译期峰值**（语法树），所以别拿它当"能不能编译出来"的
    依据 —— 2026-09-13 就是用它加 96KB 当上限算出 200KB，把板子写到了 248KB，
    结果下次开机连 park_app.py 都编译不出来（`MemoryError: allocating 160 bytes`）。
    """
    try:
        return cur - gc_free
    except Exception:
        return 0


def auto_tune_gc_heap():
    """GC 堆**体检**：只读 + 只许抬高，**永不自动压小**。返回 True = 需要冷启动。

    两条 2026-09-13 定案（详见文件末尾常量区的注释）：
      ① GC 堆与系统堆**是 1:1 的真交易**（同一个池子，开机 `malloc(gc_heap_size)`），
         但写入**重启后才生效**（只写 freq.conf，见 Maix_utils.c）；
      ② **压过头的代价是板子起不来**（248KB 时 park_app.py 编译期就 MemoryError），
         而真实编译下限**还没测出来**。
    ⇒ 本函数只做三件事：打内存底账、识别软重启（跳过模型）、把**过小**的 GC 堆抬回
      固件默认值。系统堆够不够装模型，交给 `kpu_load()` 用真实数字报出来。
    """
    global _KPU_SKIP_REASON
    if not HEAP_TUNE:
        return False
    u, src = _maix_utils()
    if u is None:
        print("[MEM] maix.utils not found -> skip the heap check")
        return False
    free, _ = _sys_heap_free()
    if free < 0:
        print("[MEM] heap_free unavailable (%s) -> skip the heap check" % src)
        return False
    try:
        cur = u.gc_heap_size()
    except Exception:
        cur = 0
    try:
        gc_free = gc.mem_free()
    except Exception:
        gc_free = 0
    used = _gc_floor(cur, gc_free)
    print("[MEM] boot: sys_free=%d gc_heap=%d gc_free=%d (%s)"
          % (free, cur, gc_free, src))
    if cur:
        print("[MEM] park_app.py holds %d B of the %d B GC heap (the compile-time"
              " syntax tree needs much more, and is NOT visible here)"
              % (used, cur))
    print("[MEM] system heap: have %d, models+weight+camera want ~%d -> %s"
          % (free, HEAP_TUNE_NEED,
             "OK" if free >= HEAP_TUNE_NEED
             else "short by %d" % (HEAP_TUNE_NEED - free)))
    if not cur:
        print("[MEM] gc_heap_size() unreadable -> skip the heap check")
        return False
    if free < COLD_BOOT_MIN_FREE:
        # ⛔ 不是冷启动（IDE Run/软重启）——上一次的 KPU 模型内存没还。
        # 这种状态下再往下走只有三个后果：读模型几十秒、权重必然 MemoryError、
        # 重试不断泄漏（2026-09-13 真机实测：十几分钟后 GC 堆只剩 6112 字节）。
        _KPU_SKIP_REASON = "soft boot: POWER-CYCLE"
        print("[MEM] sys_free=%d is far below a cold boot (%d) -> this is a SOFT reset"
              " (IDE Run / Ctrl-D): the previous run still owns the KPU model memory,"
              " which is never returned. Models are skipped this boot."
              % (free, COLD_BOOT_MIN_FREE))
        print("[BOOT] >>> UNPLUG AND REPLUG THE BOARD (cold boot), then run again <<<")
        return False
    if cur >= HEAP_TUNE_GC_MIN:
        # 正常路径：什么都不做。**压小在这里没有任何收益，只有把板子写死的风险。**
        print("[MEM] gc_heap %d B >= %d B -> fine, NOT touching it (shrinking the GC"
              " heap DOES buy system heap 1:1, but only after a reboot, and the"
              " compile floor is unmeasured: never do it unattended)"
              % (cur, HEAP_TUNE_GC_MIN))
        return False
    # 唯一会写的一步：GC 堆小到可能编译不出 park_app.py ⇒ 抬回固件默认值（只赚不赔）
    print("[MEM] gc_heap %d B is BELOW %d B -> park_app.py may fail to COMPILE;"
          " raising it back to %d B" % (cur, HEAP_TUNE_GC_MIN, HEAP_TUNE_GC_RESTORE))
    try:
        status, before, after = _apply_gc_heap(HEAP_TUNE_GC_RESTORE)
    except Exception as e:
        print("[MEM] raising the GC heap failed: %r" % (e,))
        return False
    print("[MEM] sys_free %d -> %d (%s)" % (before, after, status))
    if status == "deferred":
        print("[BOOT] the GC heap raise is not live yet -> POWER-CYCLE the board"
              " (it persists, so this happens only once)")
        return True
    if status == "live":
        print("[MEM] GC heap raised -> keep booting")
        return False
    print("[MEM] could not raise the GC heap -> continuing as is (it may still be too"
          " small to boot park_app.py: use k210_fw/gc_restore.py if that happens)")
    return False


