def _load_weight(rec, weight_path, want=None):
    """装权重。这是全场最吃系统堆的一步（1.4MB 连续块）。

    只有一次机会：**再也不做"压小 GC 堆再试"**（2026-09-13：GC 堆与系统堆是 1:1 交易，
    但写入要重启才生效、编译下限未知；写进 flash 的小值会让下次开机连 park_app.py 都编译
    不出来，见常量区注释）。
    失败就把余量和原因原样交回 `kpu_load()`，由它给提示/放弃。
    顺序关键：**相机必须在权重之后才开**（相机缓冲 ~300KB，先开会把权重挤掉）。
    """
    # ⛔ 这里**不再** stat（2026-09-13：模型读完之后的第一次 uos.stat() 把板子挂死了，
    # 而那之前的统计早就把三个文件大小都量过了）→ 直接用调用方给的值。
    if want is None:
        want = _stat_size(weight_path)
    free, _src = _sys_heap_free()
    print("[KPU] weight needs %dB; sys_free=%d -> slack=%d"
          % (want, free, free - want))
    t0 = utime.ticks_ms()
    try:
        _sd_eta("weight", want)
        print("[DBG] > rec.lp_recog_load_weight_data(%s)" % weight_path)
        rec.lp_recog_load_weight_data(weight_path)
        print("[DBG] < rec.lp_recog_load_weight_data returned in %d ms"
              % utime.ticks_diff(utime.ticks_ms(), t0))
        print("[KPU] weight ok")
        return True
    except Exception as e:
        print("[KPU] weight failed after %d ms: %r"
              % (utime.ticks_diff(utime.ticks_ms(), t0), e))
        print("[KPU] note: this is a SYSTEM heap shortage; the GC heap knob cannot"
              " help (see the constants block) - the only real levers are LCD_PREVIEW"
              " and CAM_W/CAM_H")
        return False


def _load_detect_cleanup(det, det_path, rec, weight_path):
    """识别(含权重)已就绪后，再试"检测模型要不要保留"。

    两块模型+权重同时驻留在厂家固件上装不下（实测差 843KB/339KB 两档都不够），
    所以：能装就留着（有检测框画得更准），装不下就放掉检测模型——
    降级为"整帧/固定 ROI 送识别"，业务不受影响。返回 True=检测模型保留。
    """
    if det is None:
        return False
    try:
        heap_report("before adding det")
        det.load_kmodel(det_path)
        det.init_yolo2(YOLO_ANCHOR, anchor_num=len(YOLO_ANCHOR) // 2,
                       img_w=CAM_W, img_h=CAM_H, net_w=CAM_W, net_h=CAM_H,
                       layer_w=KPU_DET_LAYER_W, layer_h=KPU_DET_LAYER_H,
                       threshold=KPU_DET_THRESHOLD, nms_value=KPU_DET_NMS,
                       classes=0)
        print("[KPU] det model also loaded (detect boxes available)")
        heap_report("after det")
        return True
    except Exception as e:
        print("[KPU] det model does not fit alongside recog+weight: %r" % (e,))
        try:
            if hasattr(det, "deinit"):
                det.deinit()
        except Exception:
            pass
        try:
            del det
        except Exception:
            pass
        gc.collect()
        print("[KPU] released det -> recognition-only mode (whole frame / ROI)")
        return False


def kpu_load_detect():
    """试装**可选**的检测模型——必须等相机/LCD 拿到缓冲之后再调（2026-09-13）。

    为什么放到相机后面：检测模型 460KB + init_yolo2 68KB，如果它先占了内存、相机
    那 389KB 再分配就会失败 ⇒ 屏幕全黑、连预览都没有，而检测模型本来只是"锦上添
    花"。顺序倒过来最差也只是丢掉检测框（退"整帧送识别"），预览和识别照常。
    """
    global _KPU_DET, _KPU_DET_TRIED
    if ROI_MODE:
        # 固定 ROI 直识别：不加载检测模型（省 460KB sys 堆 + init_yolo2 68KB），
        # 识别直接吃固定框。_KPU_DET_TRIED 置位防止复检。
        _KPU_DET_TRIED = True
        return False
    if _KPU_DET_TRIED or _KPU_RECOG is None or not _KPU_PATHS:
        return _KPU_DET is not None
    _KPU_DET_TRIED = True
    det_path = _KPU_PATHS[0]
    det_size = _KPU_SIZES[0] if _KPU_SIZES else _stat_size(det_path)
    if det_size <= 0:
        print("[KPU] no detect model on the card -> recognition only")
        return False
    # 先看余量再动手：det 要 460KB + init_yolo2 68KB，而 2026-09-13 实测装完
    # recog+weight 只剩 ~296KB ⇒ 直接跳过（省得去申请一块注定失败的连续内存，
    # 失败了还可能把系统堆切碎）。数字打出来，别让人猜。
    need = det_size + 80 * 1024
    free, _ = _sys_heap_free()
    if 0 <= free < need:
        print("[KPU] sys_free=%d < det needs ~%d -> skip the detect model"
              " (recognition still runs on the whole frame)" % (free, need))
        return False
    det = None
    try:
        from maix import KPU
        det = KPU()
        miss = _api_missing(det, ("load_kmodel", "init_yolo2",
                                  "run_with_output", "regionlayer_yolo2"))
        print("[KPU] detect api missing=%s" % miss)
        if miss:
            print("[KPU] detect API incomplete -> recognition only")
            det = None
    except Exception as e:
        print("[KPU] KPU() #1 construct failed: %r" % (e,))
        det = None
    if _load_detect_cleanup(det, det_path, _KPU_RECOG, _KPU_PATHS[2]):
        _KPU_DET = det
        return True
    return False


def kpu_load():
    """加载模型，顺序按内存实测的最佳序（2026-09-13）：

        ① 挂 SD（固件不挂我们这块板的卡，走内联 SPI-FAT）
        ② 识别模型 + 权重（**先装模型，后开相机**——相机缓冲 389KB 会挤掉权重）
        ③ 之后才让 App 开相机/LCD
        ④ 相机就位后再试**可选**的检测模型（kpu_load_detect，装不下就放掉）

    失败不阻塞预览，按 KPU_RETRY_MS 重试**但最多 KPU_MAX_TRIES 次**；内存不够这类
    "再试也没用"的失败直接放弃（见 _kpu_fail）。失败原因同时进 _KPU_ERR 上屏。"""
    global _KPU_RECOG, _KPU_PATHS, _KPU_SIZES, _KPU_LOADED, _KPU_ERR, _KPU_TRIES
    if _KPU_LOADED:
        return True
    if _KPU_GIVE_UP:
        return False        # 彻底放弃：再来一遍只会重读 SD 并继续漏内存
    if _KPU_SKIP_REASON:
        # 划分还没生效，装了也装不下（而且可能把系统堆碎片化）→ 只报一次原因、直接
        # 上屏（屏顶红字会一直闪这条），**不排重试**（每 10s 刷同一句没意义）。
        _KPU_ERR = _KPU_SKIP_REASON
        _dbg_once("kpu_skip", _KPU_SKIP_REASON)
        try:
            if _APP is not None:
                _APP.status = {"kind": "nomodel", "ts": utime.ticks_ms(),
                               "reason": _KPU_SKIP_REASON}
        except Exception:
            pass
        return False
    if _KPU_LOAD_FAILED and utime.ticks_diff(utime.ticks_ms(), _KPU_RETRY_AT) < 0:
        return False        # 上次失败且仍在重试窗口内
    _KPU_TRIES += 1
    if _KPU_TRIES > 1:
        print("[KPU] retry %d/%d" % (_KPU_TRIES, KPU_MAX_TRIES))
    # ① 找模型文件：按 KPU_DIRS 顺序解析（卡根目录也认），找不到就报 -1
    det_path, recog_path, weight_path, found = _resolve_models()
    if not found:
        if sd_ensure_mounted():
            det_path, recog_path, weight_path, found = _resolve_models()
    paths = (det_path, recog_path, weight_path)
    sizes = (_stat_size(det_path), _stat_size(recog_path),
             _stat_size(weight_path))
    if found:
        if ROI_MODE:
            # 固定 ROI：检测模型不参与，det 不 stat（打印里也不提，免得看成"缺文件"）
            print("[KPU] model dir=%s ROI_MODE=1 -> recog=%d weight=%d (bytes;"
                  " det not needed)" % (found, sizes[1], sizes[2]))
        else:
            print("[KPU] model dir=%s det=%d recog=%d weight=%d (bytes)"
                  % ((found,) + sizes))
    else:
        print("[KPU] files det=%d recog=%d weight=%d (bytes, -1=not found)"
              % sizes)
        print("[KPU] searched dirs: %s" % (KPU_DIRS,))
        _mount_diag()          # /sd 到底挂没挂 + 各根目录真实内容
        return _kpu_fail("sd models missing")
    if _stat_size(weight_path) <= 0:
        return _kpu_fail("no weight file")
    # ② 识别模型 + 权重（省内存序：模型先于相机）
    rec = _load_recog_api(paths)
    if rec is None:
        return _kpu_fail("recog load failed")
    if not _load_weight(rec, weight_path, sizes[2]):
        try:
            del rec
        except Exception:
            pass
        gc.collect()
        # 差的就是几十~一两百 KB 时，这两颗常量开关是**当场**就能腾出系统堆的旋钮；
        # GC 堆划分也是一条真路（1:1 交易），但要重启才生效、且编译下限未知，不能
        # 自动动（见 auto_tune_gc_heap 的说明）；换 Lite 固件是系统堆这边最大的一笔。
        print("[KPU] HINT if this is only ~100KB short: set LCD_PREVIEW=0 (frees the"
              " LCD buffer) and-or keep CAM_FRAMEBUFFERS=1 (one 150KB camera frame),"
              " then save park_app.py again")
        # permanent：重试 100 次内存也不会变多，只会每次重读 SD 并再漏一个 KPU 实例
        return _kpu_fail("weight:low memory", permanent=True)
    # ③ 识别通了 → 记下来；检测模型留到相机开好之后（kpu_load_detect）再试
    _KPU_RECOG = rec
    _KPU_PATHS = paths
    _KPU_SIZES = sizes
    _KPU_LOADED = True
    _KPU_ERR = ""
    try:
        if _APP is not None:
            _APP.status = {"kind": "ready", "ts": utime.ticks_ms(), "reason": ""}
    except Exception:
        pass
    print("[KPU] models ready mem_free=%d sys_free=%d"
          % (gc.mem_free(), _sys_heap_free()[0]))
    return True


def _extend_box(x, y, w, h, scale):
    """车牌框按比例外扩并夹到画面内（参考例程 extend_box）。"""
    x1 = int(x - scale * w)
    x2 = int(x + w - 1 + scale * w)
    y1 = int(y - scale * h)
    y2 = int(y + h - 1 + scale * h)
    x1 = x1 if x1 > 0 else 0
    x2 = x2 if x2 < (CAM_W - 1) else (CAM_W - 1)
    y1 = y1 if y1 > 0 else 0
    y2 = y2 if y2 < (CAM_H - 1) else (CAM_H - 1)
    return x1, y1, x2 - x1 + 1, y2 - y1 + 1


def _cap_box(x, y, w, h, max_px, iw, ih):
    """框**等比缩小、保持中心**到 w*h ≤ max_px，并夹回画面内（`CROP_MAX_PIXELS` 用）。

    ⛔ 2026-09-16 真机：板子第一轮之后再没成功过 —— `img.cut()` 要从 **GC 堆**拿一块
    w*h*2 的**连续**内存，而 GC 不压缩，松框的 54,720 B 整块在堆被切碎后永远拿不到
    （`probe_cut=0` / `probe_recog=1`，总空闲却是 378 KB ⇒ 碎片，不是泄漏）。
    缩到"探针证明拿得到"的尺寸即可；顺带车牌在 208x64 里占得更满（识别本来就要紧框）。
    框本来就 ≤ 上限 ⇒ 原样返回（已标定好的机位一个像素都不变）。"""
    if max_px <= 0 or w <= 0 or h <= 0 or w * h <= max_px:
        return x, y, w, h
    k = (float(max_px) / float(w * h)) ** 0.5
    nw = int(w * k)
    nh = int(h * k)
    if nw < 8:
        nw = 8
    if nh < 8:
        nh = 8
    nx = x + (w - nw) // 2
    ny = y + (h - nh) // 2
    nx = 0 if nx < 0 else (iw - nw if nx + nw > iw and iw > nw else nx)
    ny = 0 if ny < 0 else (ih - nh if ny + nh > ih and ih > nh else ny)
    return nx, ny, nw, nh


_recog_crop_fail_n = 0    # 失败计数：持续失败只打首现+每20次，不刷屏也不误导
_preview_fail_n = 0       # 同上：预览丢帧限频上报（2026-09-16，见 _preview_drop）


def _gc_probe(nbytes):
    """能不能**真的**从 GC 堆里拿到这么大一块连续内存（bytearray 试分配）。

    ⛔ 2026-09-16 真机：`MemoryError('Out of normal MicroPython Heap Memory!')` 出现在
    `free=354784 sysfree=1265664` 的时候 —— 两个堆的"剩余"都很大却要不到一块 55KB。
    `gc.mem_free()` 报的是**总剩余**，碎片化时它会骗人，于是"到底哪个池子要不到"变成
    猜谜，也就没法决定该抬 `gc_heap` 还是该减相机占用。所以失败行里直接给出试分配结果：
      probe_cut=0   ⇒ GC 堆里连 `ROI_W×ROI_H×2` 的连续块都没有（→ 抬 gc_heap / 收紧 ROI）
      probe_recog=0 ⇒ 连 208x64 都给不出（GC 堆已经碎到模型输入都放不下）
    绝不抛异常（它自己就活在异常处理里）。"""
    try:
        gc.collect()
        b = bytearray(nbytes)
        del b
        return True
    except Exception:
        return False


def _gc_collect():
    """收一次垃圾；`gc` 被测试替身换掉时也绝不许抛（它活在分配前的关键路径上）。"""
    try:
        gc.collect()
    except Exception:
        pass


def _recog_crop(img, x, y, w, h):
    """切车牌 -> (必要时 resize 208x64) -> (hmirror) -> pix_to_ai；
    返回可直接送识别模型的 image；失败返回 None（不打断检测循环）。

    ⛔ 2026-09-16 真机定案：**这条链上每一步都是一块 ~26KB 的图缓冲，而 GC 堆不压缩**
    ⇒ 512KB 的堆被开机这些对象切到"最大连续块 ≈26KB"之后，**第二笔分配就挂**：
      `stage=pix_to_ai 200x66 ... probe_cut=1 probe_recog=0 free=380032`
    （cut/resize/hmirror 都成功了，死在 pix_to_ai）。所以省内存四处：
      ① 入口 `gc.collect()`；② 切出来**刚好** 208x64 时**跳过 resize**；
      ③ resize 之后立刻 `del` 掉大图；④ **每次大分配前再收一次**（②③之外的最后防线）。
    根治手段在启动器：`GC_SET` 512KB→768KB（见 main.py 的注释）。框的上限
    `CROP_MAX_PIXELS` 把第一笔分配从 54,720B 压到 26,400B。
    失败行必须说清**哪一步**、要了多少字节、试分配能不能成（stage=/want=/probe_*）。"""
    global _recog_crop_fail_n
    stage = "cut"
    try:
        _gc_collect()
        lp_img = img.cut(x, y, w, h)
        if lp_img is None or lp_img.width() <= 2 or lp_img.height() <= 2:
            return None
        if lp_img.width() == RECOG_W and lp_img.height() == RECOG_H:
            rimg = lp_img                 # 已经是模型输入尺寸：resize 纯属浪费内存
        else:
            stage = "resize"
            _gc_collect()
            rimg = lp_img.resize(RECOG_W, RECOG_H)
            del lp_img
        if RECOG_HMIRROR:
            stage = "hmirror"
            rimg.replace(hmirror=True)
        stage = "pix_to_ai"
        _gc_collect()
        rimg.pix_to_ai()
        _recog_crop_fail_n = 0
        _dbg_once("crop_ok", "crop %dx%d->%dx%d ok %s"      # 每次开机一行基线
                  % (w, h, RECOG_W, RECOG_H, _mem2()))
        return rimg
    except Exception as e:
        _recog_crop_fail_n += 1
        if _recog_crop_fail_n <= 3 or _recog_crop_fail_n % 20 == 0:
            print("[DBG] recog_crop: stage=%s %dx%d want=%dB probe_cut=%d"
                  " probe_recog=%d %r %s (hint: tighter ROI_*, or raise GC_SET"
                  " in main.py)"
                  % (stage, w, h, w * h * 2,
                     1 if _gc_probe(w * h * 2) else 0,
                     1 if _gc_probe(RECOG_W * RECOG_H * 2) else 0,
                     e, _mem2()))
        return None


def recognize_frame(img):
    """对一帧 RGB565 画面做 检测 -> 裁剪 -> 逐位识别。
    返回 {"plate": 中文车牌(如 粤B12345), "plate_ascii": YueB12345,
          "confidence", "ts", "error", "det": 检测框数, "ms": 本周期耗时,
          "boxes": [(x,y,w,h), ...] 外扩后的检测框}。
    ⚠️ 本函数不改画面：框/文字由 App.overlay 叠加到"预览帧"上（板载屏与
    IDE 显示的是预览帧，画在识别帧上会看不到）。"""
    t0 = utime.ticks_ms()
    ts = t0
    if INFER_MODE != "A":
        return {"plate": None, "confidence": 0.0, "ts": ts, "error": "no_plate",
                "det": -1, "ms": 0, "boxes": []}
    if not kpu_load():
        return {"plate": None, "confidence": 0.0, "ts": ts,
                "error": "model_unavailable", "det": -1, "ms": 0, "boxes": [],
                "kpu_err": _KPU_ERR or "model unavailable"}
    kpu_load_detect()       # 首次成功加载后补试检测模型（相机此时已就位）
    if _KPU_DET is not None:
        # 正常：检测模型出车牌框，再逐框裁剪做字符识别
        try:
            _KPU_DET.run_with_output(img)
            lps = _KPU_DET.regionlayer_yolo2() or []
        except Exception as e:
            _dbg_once("detect", "exception=%r" % (e,))
            return {"plate": None, "confidence": 0.0, "ts": ts,
                    "error": "detect_error", "det": -1,
                    "ms": utime.ticks_diff(utime.ticks_ms(), t0), "boxes": []}
    else:
        # 降级/ROI：无检测模型（ROI_MODE=1）→ 只对固定区域送识别。
        # ⭐ 2026-09-15 定案：固定机位下车牌区域基本不变，逐帧 YOLOv2 全图找框
        # 冗余；固定框直识别省内存（解 JPEG OOM）、省推理、根除 det=0。
        # 不裁剪整帧：范围固定反而识别更稳（背景噪声被排除在 ROI 外）。
        w_img, h_img = img.width(), img.height()
        if ROI_MODE:
            x = int(ROI_X * w_img)
            y = int(ROI_Y * h_img)
            w = int(ROI_W * w_img)
            h = int(ROI_H * h_img)
            x = 0 if x < 0 else (w_img - 1 if x >= w_img else x)
            y = 0 if y < 0 else (h_img - 1 if y >= h_img else y)
            w = 1 if w < 1 else (w_img - x if x + w > w_img else w)
            h = 1 if h < 1 else (h_img - y if y + h > h_img else h)
            # ⛔ 单块上限在这里做（不是在做 cut 的时候）：`boxes` 是 overlay 画黄框用的，
            # 只有"送模型的框"和"画给操作员看的框"是同一个，现场调框才不会骗人。
            bx, by, bw, bh = _cap_box(x, y, w, h, CROP_MAX_PIXELS, w_img, h_img)
            if (bx, by, bw, bh) != (x, y, w, h):
                _dbg_once("roi_cap",
                          "box %dx%d (cut %dB) is over the %d px cap -> centred %dx%d"
                          " (cut %dB); put the plate in the MIDDLE of the frame or"
                          " shrink ROI_*"
                          % (w, h, w * h * 2, CROP_MAX_PIXELS, bw, bh, bw * bh * 2))
            x, y, w, h = bx, by, bw, bh
            # 把这块 ROI 的**内存代价**一起打出来：cut 就是 w*h*2 字节（RGB565），
            # 板子上切图 MemoryError 时，这行告诉你"收紧黄框"能省下多少（ROI_EXTEND=0
            # 时这个数就是精确的 cut 大小）。
            _dbg_once("roi", "fixed ROI=(%d,%d,%d,%d) img=%dx%d cut=%dB"
                      % (x, y, w, h, w_img, h_img, w * h * 2))
            lps = [(x, y, w, h)]
        else:
            # 原始降级：整帧当车牌送识别（要求车牌占满画面且摆正，最差兜底）
            _dbg_once("detect", "no detect model, feeding the whole frame")
            lps = [(0, 0, w_img, h_img)]
    # 检测结果的**直接证据**（2026-09-14）。`[RECOG] det=0` 本身说不出原因，必须能分清
    # 三种情况：① 模型跑了但一个候选都没有（画面里没车牌／方向不对）；② 有候选但置信度
    # 低于阈值（阈值问题）；③ 检测根本没跑（异常/没模型，前面已报）。`top=` 就是那个数字
    # ——把 `KPU_DET_THRESHOLD` 临时降到 0.05 再看这行，②③ 立刻分开。只打一次，不刷屏。
    if _KPU_DET is not None:
        if lps:
            _dbg_once("det_hit", "[DET] n=%d top=%.3f thr=%.2f img=%dx%d"
                      % (len(lps),
                         max([p[5] for p in lps if len(p) > 5] or [0.0]),
                         KPU_DET_THRESHOLD, CAM_W, CAM_H))
        else:
            _dbg_once("det_empty", "[DET] n=0: no candidate above thr=%.2f img=%dx%d."
                      " If thr=0.05 also gives n=0 the model sees nothing"
                      " plate-like -> point it at a plate / check the camera"
                      " direction (vendor example sets sensor.set_vflip(True))."
                      % (KPU_DET_THRESHOLD, CAM_W, CAM_H))
    best = None             # (conf, plate, plate_ascii)，多个框取最高分
    boxes = []              # 外扩后的框，供 overlay 画图
    stage = "extend"        # 死在哪一步（外层兜底要能说清，见下面的 recog_box）
    for lp in lps:
        try:
            # 固定 ROI 是自己框的，不再外扩（见 ROI_EXTEND）；检测框才需要 8% 外扩
            stage = "extend"
            x, y, w, h = _extend_box(lp[0], lp[1], lp[2], lp[3],
                                     ROI_EXTEND if ROI_MODE else KPU_DET_EXTEND)
            boxes.append((x, y, w, h))
            stage = "crop"
            rimg = _recog_crop(img, x, y, w, h)
            if rimg is None:
                continue
            # ⛔ 两次 C 调用各自兜底（2026-09-15 真机教训）：原来整段框循环只有**一个**
            #    except，于是日志里只有一句 `recog_box: exception=TypeError("unsupported
            #    types for __mod__: '', 'tuple'")` —— 分不清是 run_with_output 还是
            #    lp_recog 抛的，而那句报错**不是我们的代码**（AST 扫过：park_app.py 里所有
            #    `%` 都是整数取模，没有动态格式串）⇒ 只能靠定位到"哪一次 C 调用"再往下查。
            stage = "run"
            try:
                _KPU_RECOG.run_with_output(rimg)
            except Exception as e:
                _dbg_once("recog_run", "run_with_output failed: %r (crop %dx%d sent"
                          " as %dx%d) %s" % (e, w, h, rimg.width(),
                                             rimg.height(), _mem2()))
                continue
            stage = "out"
            try:
                out = _KPU_RECOG.lp_recog()
            except Exception as e:
                _dbg_once("recog_out", "lp_recog failed: %r %s" % (e, _mem2()))
                continue
            if not out or len(out) < 2:
                continue
            stage = "decode"
            idx = []
            for row in out:
                idx.append(row.index(max(row)))
            if not (0 <= idx[0] < len(PROVINCES)):
                continue
            chars = []
            nch = min(7, len(idx) - 1)   # 通常 7 位；参考例程只用前 6 位
            for k in range(1, nch + 1):
                i = idx[k]
                chars.append(ADS[i] if 0 <= i < len(ADS) else '?')
            # plate = 中文省份简称 + 字母数字（协议 UTF-8 中文车牌，如 粤B12345）
            ascii_plate = PROVINCES[idx[0]] + ''.join(chars[:6])
            zh = PROVINCE_ZH.get(PROVINCES[idx[0]], PROVINCES[idx[0]])
            plate = zh + ''.join(chars[:6])
            conf = sum(max(row) for row in out) / len(out)
            if best is None or conf > best[0]:
                best = (conf, plate, ascii_plate)
            if conf >= RECOG_CONF_TH:
                break      # 命中即出（框按置信排序）
        except Exception as e:
            _dbg_once("recog_box", "stage=%s exception=%r %s" % (stage, e, _mem2()))
            continue
        finally:
            # 卫生：参考例程每轮都显式 `del lp_img / del resize_img`，我们以前把 rimg
            # 挂在局部名上等 GC。第一轮能跑、之后每次早死（ms=9）的现象与"上一轮的
            # AI 输入图没放掉"高度吻合，故照抄例程的做法（2026-09-15）。
            try:
                del rimg
            except Exception:
                pass
    ms = utime.ticks_diff(utime.ticks_ms(), t0)
    try:
        gc.collect()       # 切图/缩放临时对象较多，识别完回收一次
    except Exception:
        pass
    if best and best[0] >= RECOG_CONF_TH:
        return {"plate": best[1], "plate_ascii": best[2],
                "confidence": round(best[0], 3),
                "ts": ts, "error": None, "det": len(lps), "ms": ms,
                "boxes": boxes}
    # ⭐ 2026-09-15 真机：`no_plate` 有**两个来源**，而日志里长得一模一样——
    #   ① `best is None`：模型压根没给出可用输出（crop 返回 None／`lp_recog` 空或
    #      太短／省份下标越界／框循环里抛异常）；
    #   ② `best[0] < RECOG_CONF_TH`：模型**认出来了**，只是置信度没过阈值。
    # 两者对策完全相反（① 查 ROI 与画面朝向，② 才是调阈值/收紧框），所以必须把
    # "最像的那个答案"带出去，否则下一次冷启动还是只能看到一句无信息的 no_plate。
    return {"plate": None, "confidence": 0.0, "ts": ts, "error": "no_plate",
            "det": len(lps), "ms": ms, "boxes": boxes,
            "best": best[1] if best else None,
            "best_ascii": best[2] if best else None,
            "best_conf": round(best[0], 3) if best else None}


def recognize(jpeg):
    """一次抓拍识别（0xC1 二进制链路专用）。
    双模型识别需要原始 image（见 recognize_frame）；此处只服务非 A 模式。"""
    ts = utime.ticks_ms()
    if INFER_MODE == "A":
        return {"plate": None, "confidence": 0.0, "ts": ts, "error": "live_only"}
    return {"plate": None, "confidence": 0.0, "ts": ts, "error": "no_plate"}


def decide(result):
    plate = result.get("plate")
    conf = result.get("confidence", 0.0)
    ts = result.get("ts")
    if plate and conf >= RECOG_CONF_TH:
        return True, {"plate": plate, "confidence": round(conf, 3), "ts": ts}
    return False, {"error": result.get("error", "no_plate")}


