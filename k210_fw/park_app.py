def _mem_budget(sizes, slack=512 * 1024):
    """模型三件套要多少内存（文件大小 + 固定余量）。

    ⚠️ 这是**保守估算**，不是精确投影：实测 `lp_detect.kmodel` 460KB 文件实吃
    约 501KB 系统堆（1.09x），识别模型更大。所以它只在"差着一个数量级"时下结论
    （本板实测 need 3.16MB vs total 2.10MB）——宁可提示换固件，也不要再去触发
    固件级 MemoryError 把板子卡死。
    """
    need = 0
    for s in sizes:
        try:
            if s > 0:
                need += s
        except Exception:
            pass
    return need + slack


def _kpu_mem_verdict(free_b, gc_b, sizes, slack=512 * 1024):
    """给（系统堆空闲, GC 堆, 模型大小表）出余量结论。返回 (need, total, tight)。"""
    need = _mem_budget(sizes, slack)
    total = (free_b if free_b > 0 else 0) + (gc_b if gc_b > 0 else 0)
    return need, total, total < need


def _maix_utils():
    """取本固件的 maix.utils。

    ⚠️ 2026-09-13 板测教训：这块 CanMV/v1.0.4 固件里**模块名是小写 `maix`**
    （`from maix import KPU` 一直好用），**没有大写 `Maix`**——照 MaixPy 老文档写
    `import Maix` 会 `ImportError: no module named 'Maix'`，于是所有内存读数全成问号。
    这里把两种写法都试一遍，返回 (utils, 名字)。"""
    for name in ("maix", "Maix"):
        try:
            u = getattr(__import__(name), "utils", None)
            if u is not None and hasattr(u, "heap_free"):
                return u, name + ".utils"
        except Exception:
            pass
    try:
        from maix import utils as u
        return u, "maix.utils(import)"
    except Exception:
        return None, ""


def _sys_heap_free():
    """(free, 来源) —— 系统堆余量。**整体兜底**：本固件的 C 层会偶发抛假异常
    （2026-09-16 真机：`maix.utils.heap_free()` 之后一句普通 print 报
    `unsupported types for __mod__: 'int', 'tuple'`，AST 扫过我们源码里
    **没有**任何非字面量格式串）⇒ 读数不许把调用方（cam_init 等）带走。"""
    try:
        u, src = _maix_utils()
        if u is None:
            return -1, src
        try:
            return u.heap_free(), src
        except Exception as e:
            return -1, "%r" % (e,)
    except Exception as e:
        return -1, "guard:%r" % (e,)


def _fw_ver():
    """固件标识：**优先 `uos.uname()`**（真正的 build 串），拿不到才退 `sys.version`。

    2026-09-14：换上官方 Lite 固件后横幅只打 "3.4.0" —— 本固件的 `sys.version`
    就只有这么点内容，用它当固件身份等于没有（而这正是我们要用来区分
    v1.0.4 / v1.0.5-4、FULL / Lite 的东西）。build 串在 `os.uname()` 里，所以先试它。
    """
    try:
        u = uos.uname()
        try:
            return ("%s; %s" % (u.release, u.version))[:64]
        except Exception:
            return ("; ".join(str(x) for x in u))[:64]
    except Exception:
        pass
    try:
        v = sys.version
        part = v.split("(", 1)
        head = part[0].strip()
        tail = part[1].split(")", 1)[0] if len(part) > 1 else ""
        return ("%s %s" % (head, tail)).strip()[:64]
    except Exception:
        return "unknown"


