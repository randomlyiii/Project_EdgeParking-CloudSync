def _api_missing(obj, names):
    """返回 obj 上缺失的方法名列表（判断固件有没有 DNK210 的 KPU 扩展 API）。"""
    miss = []
    for n in names:
        try:
            if not hasattr(obj, n):
                miss.append(n)
        except Exception:
            miss.append(n)
    return miss


def _exists(path):
    """文件是否可读：先 stat，stat 不可靠/返回 -1 时真去开一次兜底。"""
    if _stat_size(path) >= 0:
        return True
    f = None
    try:
        f = open(path, "rb")
        f.read(1)
        return True
    except Exception:
        return False
    finally:
        try:
            if f:
                f.close()
        except Exception:
            pass


