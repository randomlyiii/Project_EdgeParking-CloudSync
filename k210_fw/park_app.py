class _NullUart:
    """UART 打开失败时的占位：不崩，跑起来看到底哪一步挂了。"""
    def write(self, *a, **k):
        pass
    def any(self):
        return 0
    def read(self, *a, **k):
        return b""


def _open_uart():
    """数据口（LINK="uart" 时用板级串口 UART_ID/921600）。
    LINK="console" 时不需要 UART（走 print 文本），返回 _NullUart 占位。
    """
    try:
        from machine import UART
    except Exception:
        return _NullUart()
    if LINK != "uart":                      # console/其它模式不需要板级 UART
        return _NullUart()
    uid = UART_ID
    try:
        return UART(uid, UART_BAUD, 8, None, 1,
                    timeout=0, read_buf_len=UART_RX_BUF_LEN)
    except TypeError:
        try:
            return UART(uid, UART_BAUD, 8, None, 1, timeout=0)
        except Exception:
            return _NullUart()
    except Exception:
        return _NullUart()


class App:
    def __init__(self):
        self.uart = _open_uart()
        self.parser = FrameParser(on_frame=self.dispatch)
        self.preview = PreviewStream(self.uart.write, PREVIEW_CHUNK)
        self.busy = False
        self.hb_last = utime.ticks_ms()
        self.trigger_last = 0
        self._seqs = {}
        self.stat_last = utime.ticks_ms()
        self.stat_frames = 0
        self.stat_jlen = 0
        self.gc_last = utime.ticks_ms()
        self.recog_last = utime.ticks_ms()
        self.orient_last = utime.ticks_ms()
        self.orient_idx = -1                # -1 → 首次进 ORIENT_PROBE 打 combo=0(原始姿态)
        self.ovl = None                     # 最近一次识别结果，供 overlay 叠加显示
        # 板载屏状态条的数据源（SCREEN_STATUS=1 时每帧画到 LCD 顶部）
        self.status = {"kind": "ready", "ts": 0, "reason": ""}
        self.img_seq = 0                    # 预览帧计数（CONSOLE_IMG_EVERY 降频用）

    def tx(self, type_, payload=b""):
        seq = self._seqs.get(type_, 0)
        self._seqs[type_] = (seq + 1) & 0xFFFF
        self.uart.write(encode_frame(type_, seq, payload))

    def dispatch(self, type_, seq, payload):
        if type_ != TYPE_CMD_RECOGNIZE:
            return
        now = utime.ticks_ms()
        if self.busy:
            return
        if utime.ticks_diff(now, self.trigger_last) < TRIGGER_COOLDOWN_MS:
            return
        self.do_recognize()

    def do_recognize(self):
        self.busy = True
        self.trigger_last = utime.ticks_ms()
        try:
            jpeg = capture_jpeg()
            result = recognize(jpeg) if jpeg else {
                "plate": None, "confidence": 0.0,
                "ts": utime.ticks_ms(), "error": "no_image"}
            ok, obj = decide(result)
            if ok:
                self.tx(TYPE_RECOG_RESULT, json.dumps(obj))
            else:
                if jpeg:
                    self.preview.send_jpeg(jpeg, kind=FRAME_KIND_SNAP)
                self.tx(TYPE_RECOG_FAIL, json.dumps(obj))
        finally:
            self.busy = False

    def _preview_drop(self, why):
        """预览失败**限频**上报（首现 3 次 + 之后每 20 次一行）——自身绝不抛。

        它专门在"分配失败/写 CDC 失败"时被调用，所以这里连 print 都不能信。"""
        global _preview_fail_n
        try:
            _preview_fail_n += 1
            if _preview_fail_n <= 3 or _preview_fail_n % 20 == 0:
                print("[DBG] console preview dropped (#%d): %s (if this repeats,"
                      " lower CONSOLE_IMG_EVERY / JPEG_QUALITY)"
                      % (_preview_fail_n, why))
        except Exception:
            pass

    def console_send_jpeg(self, jpeg):
        """零线 console 文本传输：JPEG -> base64 分行走 print（MP157 解析 K2:IMG/K2:END 行）。
        ⚠️ 本固件实测 machine.UART 二进制到不了 USB；console(print) 文本可以（保真/慢）。

        ⛔ 2026-09-16：整段**绝不许把异常抛出去**。真机现象：一帧涨到 14280 字符
        （16 行 × 25ms = 400ms）后串口直接断连，且全场没有一条 Python 报错。
        预览只是"给人看"的：它在这里抛（分片格式化 / print 分配失败 / CDC 写失败），
        主循环就被掀掉、**识别一起停**，板子看起来就是"断连"。
        所以：失败只丢这一帧 + 限频打一行，绝不中断。半帧已经发出去也没关系——
        对端（`k210_link`）按"总长必须等于 K2:END 声明的长度"校验，残帧永远不会被当成图。
        """
        try:
            import binascii
            b64 = binascii.b2a_base64(jpeg).decode().rstrip("\n")
        except Exception as e:
            self._preview_drop("at b64: %r" % (e,))
            return
        try:
            for i in range(0, len(b64), CONSOLE_CHUNK):
                print("K2:IMG:%d:%s" % (i, b64[i:i + CONSOLE_CHUNK]))
                utime.sleep_ms(CONSOLE_PACE_MS)
            print("K2:END:%d" % len(b64))
        except Exception as e:
            self._preview_drop("mid-frame at %d chars: %r" % (len(b64), e))

    def console_recognize_tick(self):
        """console 模式周期识别：INFER_MODE=A 对实时帧跑本地 KPU 双模型；
        无模型时若 CONSOLE_FAKE_RESULT=1 发假车牌打通 Qt 弹卡/判定链路。结果行:
        K2:OK:<json{plate,confidence,ts}>  /  K2:NG:<json{error}>"""
        if LINK != "console":
            return
        if self.busy:
            return
        if CONSOLE_FAKE_RESULT:
            print("K2:OK:%s" % json.dumps(
                {"plate": CONSOLE_FAKE_PLATE, "confidence": CONSOLE_FAKE_CONF,
                 "ts": utime.ticks_ms()}))
            return
        if INFER_MODE != "A":
            return                          # B 模式无本地识别，不发结果
        img = capture_frame()
        if img is None:
            return
        self.busy = True                    # 识别期间暂停预览发送（与预览流解耦）
        # 屏上先显示"正在识别"，避免长期停在上一轮结论上（一眼可见）
        self.status = {"kind": "recognizing", "ts": utime.ticks_ms(),
                       "reason": ""}
        try:
            result = recognize_frame(img)
            self.ovl = result              # 缓存给 overlay（下几帧预览都会叠上）
            ok, obj = decide(result)
            # 每周期一行诊断：det=检测框数(-1=模型不可用/异常) ms=耗时
            # 这行就是"模型到底跑没跑"的直接证据（IDE 串口可见）
            # 但**已彻底放弃加载**（内存不够/软重启）时只打一次：同一句每 3s 刷一遍
            # 会把串口刷满、把真正的原因淹掉（2026-09-13 踩过）。
            # 失败原因分叉（2026-09-15）：`best_conf` 是"模型最像的那个答案"的置信度。
            # 有它 ⇒ 模型看得见车牌、只是没过阈值（调 RECOG_CONF_TH / 收紧 ROI）；
            # 没有它 ⇒ 模型什么都没输出（查 ROI 是否套住车牌 / 画面朝向）。
            extra = ""
            if not ok:
                if result.get("kpu_err"):
                    extra = " [" + result["kpu_err"] + "]"
                elif result.get("best_conf") is not None:
                    extra = (" best=%s conf=%s th=%s"
                             % (result.get("best"), result.get("best_conf"),
                                RECOG_CONF_TH))
                elif result.get("error") == "no_plate":
                    extra = " (model gave no usable output)"
            # cropfail = 连"把图切出来"都没成功的次数（成功即归零）。它 >0 时下面那句
            # `NG ... (model gave no usable output)` **不是模型说没有车牌，而是模型
            # 根本没拿到图**——2026-09-16 板子上就是这个（切图 MemoryError 每轮都挂，
            # 光看 `no_plate` 会一路查错方向）。取图失败另有 `[DBG] recog_crop` 行。
            line = ("[RECOG] det=%s ms=%s cropfail=%s %s"
                    % (result.get("det"), result.get("ms"),
                       _recog_crop_fail_n,
                       ("OK plate=%s conf=%s" % (result.get("plate"),
                                                 result.get("confidence")))
                       if ok else "NG err=%s%s" % (result.get("error"), extra)))
            if _KPU_GIVE_UP and not ok:
                _dbg_once("recog_giveup", line + "  <- models given up, see [KPU] above")
            else:
                print(line)
            if ok:
                # 结论同时上屏（绿色）：车牌 + 置信度
                self.status = {"kind": "ok", "ts": utime.ticks_ms(),
                               "plate": result.get("plate"),
                               "conf": result.get("confidence") or 0.0,
                               "reason": ""}
                print("K2:OK:%s" % json.dumps(obj))
            else:
                # 失败原因上屏（橙色）：模型没起来显示 kpu_err，否则 error
                self.status = {"kind": "fail", "ts": utime.ticks_ms(),
                               "reason": (result.get("kpu_err")
                                          or result.get("error") or "unknown")}
            # NG 不发(预览流已在发图; 云兜底/调试需要时再开)
        except Exception:
            self.status = {"kind": "fail", "ts": utime.ticks_ms(),
                           "reason": "exception"}
            raise
        finally:
            self.busy = False

    def screen_status(self, img):
        """板载屏状态条：把"识别成功没有"画在画面上（用户 2026-09-13 要求）。

        串口被 base64 预览刷满时根本看不出识别结果，所以结论直接上屏：
          NO MODEL  <原因>       红，闪烁 = 模型没加载（屏上就能看到为什么）
          READY / RECOGNIZING    黄 = 模型就绪、正在识别
          OK <车牌> <conf> <Ns前> 绿 = 识别成功
          FAIL <原因>            橙 = 识别失败
        必须画在 lcd_show() 之前（屏幕取的是这一帧的缓冲）。"""
        if not SCREEN_STATUS or img is None:
            return
        try:
            st = self.status or {}
            kind = st.get("kind") or "ready"
            txt = "READY"
            col = C_YELLOW
            if kind == "nomodel":
                # 模型没起来是最要命的状态 → 闪烁 + 直接写原因（如 sd models missing）
                if (utime.ticks_ms() // 300) & 1:
                    txt = "NO MODEL " + str(st.get("reason") or "")[:20]
                    col = C_RED
                else:
                    return
            elif kind == "recognizing":
                txt = "RECOGNIZING"
                col = C_YELLOW
            elif kind == "ok":
                age = utime.ticks_diff(utime.ticks_ms(), st.get("ts") or 0) // 1000
                txt = "OK %s %.2f %ds" % (st.get("plate") or "?",
                                          st.get("conf") or 0.0, age)
                col = C_GREEN
            elif kind == "fail":
                age = utime.ticks_diff(utime.ticks_ms(), st.get("ts") or 0) // 1000
                txt = "FAIL %s %ds" % (str(st.get("reason") or "")[:18], age)
                col = C_ORANGE
            # 底色实心条：彩字在杂乱画面上也能看清
            w = CAM_W
            try:
                w = img.width()
            except Exception:
                pass
            img.draw_rectangle(0, 0, w, STATUS_BAR_H, color=(0, 0, 0),
                               fill=True)
            img.draw_string(2, 3, txt, color=col, scale=STATUS_SCALE)
        except Exception as e:
            _dbg_once("screen_status", "exception=%r" % (e,))

    def overlay(self, img):
        """把最近一次识别结果叠画到"预览帧"上：绿框=检测到的车牌位置，
        左上角一行 ASCII 状态（板载屏/IDE/Qt 预览都能看到，证明模型在工作）。
        ⚠️ 必须在 lcd_show / compress 之前调用。"""
        if not DRAW_DETECT or img is None or not self.ovl:
            return
        r = self.ovl
        try:
            # ROI_MODE 下的那个框是**固定 ROI**，用黄色区分（现场调框就靠这一眼：
            # 黄框要刚好把车牌裹住，太松 → 字符太小识别不出，太紧 → 车牌出框）
            col = (255, 255, 0) if ROI_MODE else (0, 255, 0)
            for b in (r.get("boxes") or []):
                img.draw_rectangle(b[0], b[1], b[2], b[3], color=col)
            if r.get("plate_ascii"):
                txt = "%s %.2f" % (r["plate_ascii"], r.get("confidence", 0.0))
                col = (255, 0, 0)
            else:
                # 失败时优先显示模型失败原因（一眼定位，不必翻串口）
                txt = r.get("kpu_err") or ("det=%s %s" % (r.get("det"),
                                                          r.get("error") or ""))
                col = (255, 255, 0)
            img.draw_string(4, 4, txt, color=col, scale=1)
        except Exception as e:
            _dbg_once("overlay", "exception=%r" % (e,))

    def orient_probe_tick(self):
        """方向排查：每 ORIENT_PROBE_MS 轮换 (vflip,hmirror) 四种组合并打印编号。
        ⚠️ 走**软件层**（CAM_SW_*）——本固件传感器层 set_vflip/set_hmirror 实测无效，
        只有软件层才能保证画面真的会变。编号同时画在画面上(见 orient_label)。"""
        global CAM_SW_VFLIP, CAM_SW_HMIRROR
        now = utime.ticks_ms()
        if utime.ticks_diff(now, self.orient_last) < ORIENT_PROBE_MS:
            return
        self.orient_last = now
        self.orient_idx = (self.orient_idx + 1) & 3
        CAM_SW_VFLIP = bool(self.orient_idx & 2)
        CAM_SW_HMIRROR = bool(self.orient_idx & 1)
        v = 1 if CAM_SW_VFLIP else 0
        h = 1 if CAM_SW_HMIRROR else 0
        print("[ORIENT] combo=%d vflip=%d hmirror=%d "
              "(0=raw 1=hmirror 2=vflip 3=180)" % (self.orient_idx, v, h))

    def orient_label(self, img):
        """把当前方向组合编号画在画面上（板载屏/IDE 都能看到，免去对日志时间）。"""
        if img is None or self.orient_idx < 0:
            return
        v = 1 if (self.orient_idx & 2) else 0
        h = 1 if (self.orient_idx & 1) else 0
        try:
            img.draw_string(4, 4, "ORIENT %d v%d h%d" % (self.orient_idx, v, h),
                            color=(255, 0, 0), scale=2)
        except Exception:
            pass

    def run(self):
        print("[BOOT] park k210 fw INFER_MODE=%s LINK=%s preview=%d draw=%d probe=%d"
              " sw_vflip=%d sw_hmirror=%d"
              % (INFER_MODE, LINK, CONSOLE_PREVIEW, DRAW_DETECT, ORIENT_PROBE,
                 1 if CAM_SW_VFLIP else 0, 1 if CAM_SW_HMIRROR else 0))
        # 配置指纹（2026-09-16）：设备上跑的到底是哪一版、ROI/阈值/上限各是多少 ——
        # 开机第一屏全写清楚。现场标定值就靠**这行**读回仓库（`build=`/`roi=`/`conf_th=`），
        # 再也不用猜"我保存的到底是哪一份"。
        print("[CFG] build=%s app=%dB roi_mode=%d roi=%.3f,%.3f,%.3f,%.3f extend=%.3f"
              " cap_px=%d conf_th=%.2f img_every=%d"
              % (BUILD, _stat_size("/flash/park_app.py"), ROI_MODE, ROI_X, ROI_Y,
                 ROI_W, ROI_H, ROI_EXTEND, CROP_MAX_PIXELS, RECOG_CONF_TH,
                 CONSOLE_IMG_EVERY))
        print("[BOOT] firmware: %s" % _fw_ver())
        # ⛔ 顺序是实测定的，别改（2026-09-13 板测）：
        #   ① 先挂 SD  ② 先装识别模型+权重  ③ 有余量才加检测模型  ④ **最后**才开相机/LCD
        # 原因：相机缓冲吃 ~380KB 系统堆，而权重 1.43MB 要一大块连续内存；
        # 相机先开就会把权重挤掉（实测每次都卡在 lp_recog_load_weight_data）。
        want_kpu = (INFER_MODE == "A" and not ORIENT_PROBE)
        if want_kpu:
            heap_report("boot before sd")
            # 没卡就反复重试、**不进后续**（2026-09-16 用户要求）。返回 False 只在
            # SD_WAIT_MAX 封顶时发生，那时才退回固件自己的 SDCard 老路。
            if not sd_wait_until_mounted():
                sd_ensure_mounted()
            loaded = kpu_load()
            print("[BOOT] kpu_load -> %s" % loaded)
        else:
            # B 模式/方向排查：不需要模型，按老路子先开相机看画面
            print("[BOOT] INFER_MODE=%s probe=%d -> skipping the KPU load"
                  % (INFER_MODE, ORIENT_PROBE))
        try:
            cam_init()                      # 必须在模型之后（见上面的注释）
        except Exception as e:
            print("[WARN] cam_init failed:", e)
        # ④ 相机/LCD 拿到缓冲之后，才试可选的检测模型（挤不下就退"整帧送识别"）
        try:
            kpu_load_detect()
        except Exception as e:
            print("[WARN] kpu_load_detect failed:", e)
        print("[BOOT] entering main loop")
        while True:
            now = utime.ticks_ms()
            if not self.busy:               # 预览流常开（与推理解耦）
                img = capture_frame()
                if ORIENT_PROBE:
                    self.orient_label(img)  # 画组合编号(必须在 lcd_show 之前)
                else:
                    self.overlay(img)       # 叠最近一次识别结果(框+车牌)
                self.screen_status(img)     # 板载屏状态条(必须在 lcd_show 之前)
                lcd_show(img)               # 先上屏（compress 会原地改写 img）
                # 停发预览（CONSOLE_PREVIEW=0）时不发 base64：省 CPU，且让串口只剩诊断行。
                # ⚠️ 2026-09-14：这里原本还串了 `ORIENT_PROBE`，与 orient_label 自己的
                #    注释"（IDE 帧缓冲可见）"**自相矛盾**——方向排查恰恰必须能看见画面，
                #    否则只能靠板载屏（还得再开 LCD_PREVIEW）。所以排查模式照发；
                #    真想省带宽就把 CONSOLE_IMG_EVERY 调大。
                if LINK == "console" and not CONSOLE_PREVIEW:
                    self.stat_frames += 1
                else:
                    self.stat_frames += 1
                    # 串口预览降频（CONSOLE_IMG_EVERY>1 时每 N 帧才发一次），
                    # 屏幕/IDE 帧缓冲不受影响，只是串口不再被 base64 刷满。
                    n = CONSOLE_IMG_EVERY if CONSOLE_IMG_EVERY and CONSOLE_IMG_EVERY > 1 else 1
                    if self.img_seq % n == 0:
                        jpeg = jpeg_from(img)
                        if jpeg:
                            self.stat_jlen = len(jpeg)
                            if LINK == "console":
                                self.console_send_jpeg(jpeg)
                            else:
                                self.preview.send_jpeg(jpeg)
                    self.img_seq += 1
            if ORIENT_PROBE:                # 方向排查模式：只出图+编号，不跑识别
                self.orient_probe_tick()
                utime.sleep_ms(20)
                continue
            if LINK == "console" and utime.ticks_diff(now, self.recog_last) >= RECOG_PERIOD_MS:
                self.recog_last = now
                self.console_recognize_tick()
            n = self.uart.any()
            if n:
                data = self.uart.read(n)
                if data:
                    self.parser.feed(data)
            if utime.ticks_diff(now, self.hb_last) >= HEARTBEAT_MS:
                self.hb_last = now
                self.tx(TYPE_HEARTBEAT, bytes([1 if self.busy else 0]))
            if utime.ticks_diff(now, self.stat_last) >= STAT_PERIOD_MS:
                fps = self.stat_frames * 1000 // max(1, utime.ticks_diff(now, self.stat_last))
                _log("[stat] fps=%d jpeg=%dB mem_free=%d"
                     % (fps, self.stat_jlen, gc.mem_free()))
                self.stat_frames = 0
                self.stat_last = now
            if utime.ticks_diff(now, self.gc_last) >= GC_PERIOD_MS:
                self.gc_last = now
                gc.collect()
            utime.sleep_ms(2)


