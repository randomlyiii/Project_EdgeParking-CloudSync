def jpeg_from(img):
    """把已拍摄的 image 压成 JPEG 字节；失败返回 None（预览与抓拍共用）。

    ⚠️ 2026-09-14：原来是**静默** `except: return None`，于是 `[stat] jpeg=0B` 只告诉
    我们"预览没发出去"，一个字的原因都没有。现在失败必打一次（`_dbg_once`）——预览
    是给人看的东西，坏掉不能不出声。
    也**不再**在 compress 失败时退回 `bytes(img)`：那会把 RGB565 裸像素当成 JPEG 塞进
    预览流（对端只会解出垃圾帧），不如如实不发。
    ⚠️ 2026-09-15：三模型全加载后系统堆只剩 ~590KB，QVGA(320x240) 软件 compress
    的直接需求就够呛（实测 MemoryError 'reduce the resolution'）。预览图本来就为
    了给 Qt/IDE 看，缩到 QQVGA(160x120) 画质完全够——所以 MemoryError 时自动降级：
    原地 resize 到 1/4 面积再压一次。识别帧是 console_recognize_tick 里**独立
    snapshot** 的，不受这里 resize 影响；lcd 已先 display（调用序见 run）。
    """
    try:
        if img is None:
            return None
        if JPEG_HW:
            return bytes(img)
        try:
            comp = img.compress(quality=JPEG_QUALITY)
        except MemoryError:
            _dbg_once("jpeg_degrade",
                      "QVGA compress OOM -> resize QQVGA then retry")
            img.resize(CAM_W // 2, CAM_H // 2)
            comp = img.compress(quality=JPEG_QUALITY)
        if comp is None:
            _dbg_once("jpeg_none", "img.compress(quality=%d) returned None"
                      % JPEG_QUALITY)
            return None
        return bytes(comp)
    except Exception as e:
        _dbg_once("jpeg_fail", "img.compress(quality=%d) failed: %r"
                  % (JPEG_QUALITY, e))
        return None


