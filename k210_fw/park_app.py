def _sensor_setup(sensor, w, h):
    """按给定尺寸配置相机。返回 None=成功，否则返回异常。

    帧缓冲数量**放在 set_framesize 之前**设：`set_framesize` 才是真正分配缓冲的
    那一步（2026-09-13 板测：ENOMEM 就出在它身上），放在后面就来不及了。
    """
    fn = getattr(sensor, "set_framebuffernum", None)
    if fn is None:
        print("[MEM] this firmware has no sensor.set_framebuffernum")
    else:
        try:
            fn(CAM_FRAMEBUFFERS)
            print("[MEM] set_framebuffernum(%d) before set_framesize"
                  % CAM_FRAMEBUFFERS)
        except Exception as e:
            print("[MEM] set_framebuffernum(%d) failed: %r"
                  % (CAM_FRAMEBUFFERS, e))
    table = {(160, 120): sensor.QQVGA, (320, 240): sensor.QVGA,
             (640, 480): sensor.VGA}
    try:
        sensor.set_pixformat(sensor.RGB565)
        sensor.set_framesize(table.get((w, h), sensor.QVGA))
        # ⚠️ 方向必须放在 set_framesize **之后**（2026-09-14 改）：参考例程的顺序是
        #    set_framesize → set_pixformat → set_vflip，而 set_framesize 会重写传感器
        #    窗口/寄存器。我们以前把它俩放在 set_framesize **之前** ⇒ 这极可能就是当年
        #    "传感器层翻转实测无效（四组合画面都不变）"的真正原因——不是固件不支持，
        #    是**被后一次 set_framesize 覆盖了**。换 Lite 固件后正好重测。
        if CAM_VFLIP:
            sensor.set_vflip(True)
        if CAM_HMIRROR:
            sensor.set_hmirror(True)
        print("[CAM] %dx%d RGB565 sensor_vflip=%s sensor_hmirror=%s"
              " sw_vflip=%s sw_hmirror=%s"
              % (w, h, CAM_VFLIP, CAM_HMIRROR, CAM_SW_VFLIP, CAM_SW_HMIRROR))
        return None
    except Exception as e:
        return e


def cam_init():
    """开 LCD/相机：**每一步打系统堆余量**，内存不够就降一档（绝不 deinit 再重试）。

    2026-09-13 真机定案（makerobo v1.0.4 FULL 镜像，系统堆 ~2504KB；换 Lite 镜像能
    多出约 520KB，见 fw_probe.py）：
        识别模型 697512B + 权重 1498500B = **约 2145KB** ⇒ 只剩 ~300KB 给 LCD+相机；
        **LCD 面板缓冲自己就吃 152KB**（= 一帧 QVGA RGB565），相机的 QVGA 缓冲要 ~300KB
        ⇒ "LCD + QVGA 相机 + 双模型"数学上不成立（实测 `OSError(12,)` ENOMEM）。
    ⛔ **不能再有 `lcd.deinit()` 这一手**：实测"放掉 LCD 再重配相机"会**硬故障**
       （`EPC 0x8006d722 / Cause 0x0`，板子直接死给你看）。所以 LCD 开关是**进函数前
       就定死的**，之后只降相机尺寸，不碰 LCD。
        `LCD_PREVIEW=0`（默认）→ QVGA，识别最好、板载屏黑；想要板载屏就把
        `LCD_PREVIEW=1`，那样 QVGA 会 ENOMEM 并自动降到 QQVGA(160x120)，画面小而糊。
    """
    import sensor
    global CAM_W, CAM_H
    free0 = _sys_heap_free()[0]
    print("[MEM] cam_init: sys_free=%d before anything" % (free0,))
    if LCD_PREVIEW:
        try:
            import lcd
            lcd.init()
            lcd.clear(lcd.RED)
        except Exception as e:
            print("[WARN] lcd init failed:", e)
        free1 = _sys_heap_free()[0]
        print("[MEM] cam_init: sys_free=%d after lcd.init (panel buffer took %d B;"
              " QVGA camera needs ~%d B, so expect ENOMEM and a QQVGA fallback)"
              % (free1, free0 - free1, 2 * CAM_W * CAM_H * 2))
    sensor.reset()
